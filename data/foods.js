export function normalizeFoodSearch(value = "") {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase()
    .replace(/[-'’]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function getFoodSearchTerms(food, currentLanguage = "en") {
  const currentLanguageTerms = food.aliases?.[currentLanguage] ?? [];

  const otherLanguageTerms = Object.entries(food.aliases ?? {})
    .filter(([language]) => language !== currentLanguage)
    .flatMap(([, terms]) => terms);

  return {
    currentLanguageTerms: currentLanguageTerms.map(normalizeFoodSearch),
    otherLanguageTerms: otherLanguageTerms.map(normalizeFoodSearch),
  };
}

