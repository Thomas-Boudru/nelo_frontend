export function normalizeVaccineSearch(value = "") {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase();
}

export function getVaccineSearchTerms(vaccine, currentLanguage = "en") {
  const normalizedLanguage = currentLanguage.toLowerCase().split("-")[0];

  const currentLanguageTerms =
    vaccine.searchTerms?.[normalizedLanguage] ?? vaccine.searchTerms?.en ?? [];

  const otherLanguageTerms = Object.entries(vaccine.searchTerms ?? {})
    .filter(([language]) => language !== normalizedLanguage)
    .flatMap(([, terms]) => terms);

  return {
    currentLanguageTerms: currentLanguageTerms.map(normalizeVaccineSearch),
    otherLanguageTerms: otherLanguageTerms.map(normalizeVaccineSearch),
  };
}

export function searchVaccines(
  vaccines,
  search,
  currentLanguage = "en",
  getTranslatedName = (vaccine) => vaccine.translationKey,
) {
  const normalizedSearch = normalizeVaccineSearch(search);

  if (!normalizedSearch) {
    return vaccines;
  }

  return vaccines
    .map((vaccine) => {
      const translatedName = normalizeVaccineSearch(getTranslatedName(vaccine));

      const { currentLanguageTerms, otherLanguageTerms } =
        getVaccineSearchTerms(vaccine, currentLanguage);

      const isExactMatch =
        translatedName === normalizedSearch ||
        currentLanguageTerms.some((term) => term === normalizedSearch);

      const isCurrentLanguageMatch =
        translatedName.includes(normalizedSearch) ||
        currentLanguageTerms.some((term) => term.includes(normalizedSearch));

      const isOtherLanguageMatch = otherLanguageTerms.some((term) =>
        term.includes(normalizedSearch),
      );

      const score = isExactMatch
        ? 3
        : isCurrentLanguageMatch
          ? 2
          : isOtherLanguageMatch
            ? 1
            : 0;

      return {
        vaccine,
        score,
      };
    })
    .filter(({ score }) => score > 0)
    .sort((first, second) => second.score - first.score)
    .map(({ vaccine }) => vaccine);
}
